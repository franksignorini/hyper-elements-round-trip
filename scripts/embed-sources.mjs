// Copies the template's source files into a module the studio can import, so the
// in-browser editor starts from exactly what is on disk. Runs before dev and build;
// `--watch` keeps it in step while `npm run dev` is running.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { watch } from "node:fs";

const files = ["Newsletter.tsx", "theme.ts", "issue.json"];
const OUT = "src/generated/sources.ts";

async function embed() {
  const entries = {};
  for (const file of files) entries[file] = (await readFile(`template/${file}`, "utf8")).replace(/\r\n/g, "\n");
  const text =
    `// Generated by scripts/embed-sources.mjs from template/. Do not edit.\n` +
    `export const TEMPLATE_SOURCES = ${JSON.stringify(entries, null, 2)} as const;\n` +
    `export type TemplateFile = keyof typeof TEMPLATE_SOURCES;\n`;
  await mkdir("src/generated", { recursive: true });
  const old = await readFile(OUT, "utf8").catch(() => "");
  if (old !== text) {
    await writeFile(OUT, text);
    console.log(`[embed-sources] embedded ${files.length} template files`);
  }
}

await embed();
if (process.argv.includes("--watch")) {
  let timer;
  watch("template", () => {
    clearTimeout(timer);
    timer = setTimeout(() => embed().catch((e) => console.error(e)), 150);
  });
}
